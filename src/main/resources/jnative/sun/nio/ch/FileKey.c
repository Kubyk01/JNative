/*
 * sun.nio.ch.FileKey — native entry points.
 *
 * ============================================================================
 * Why this file exists
 * ============================================================================
 *
 * The class declares two native methods:
 *
 *     private native void init(FileDescriptor fd) throws IOException;
 *     private static native void initIDs();
 *
 * init is called from FileKey.create(FileDescriptor), the public
 * factory that the JDK's own file-locking code uses to derive a stable
 * key from an open descriptor. initIDs is called from the class's
 * static initializer. The LLVM emitter records a call site for each in
 * the generated IR, so without definitions in the linked executable
 * clang rejects sun/nio/ch/FileKey.ll with
 *
 *     error: use of undefined value
 *         '@__jnative_fn_sun_nio_ch_FileKey_init__Ljava_io_FileDescriptor__V'
 *
 * ============================================================================
 * What the reference implementation does
 * ============================================================================
 *
 * On HotSpot, FileKey is the (device, inode) pair that uniquely
 * identifies an open file across the process. Its native side calls
 * fstat(2) on the raw descriptor, extracts st_dev and st_ino, and
 * stores them into the two long fields. The Java-side hashCode and
 * equals methods then compare FileKey instances by those two values,
 * so two descriptors that refer to the same underlying file compare
 * equal even when the paths they were opened through are different —
 * which is what FileChannel.tryLock / lock rely on to detect
 * overlapping locks correctly.
 *
 * initIDs caches the JNI field IDs of st_dev and st_ino.
 *
 * ============================================================================
 * Behaviour in this runtime
 * ============================================================================
 *
 * This runtime has a real POSIX file layer: FileInputStream,
 * FileOutputStream, FileChannel, and FileDescriptor all work on raw
 * kernel descriptors obtained through the standard system calls. The
 * fstat(2) needed to populate FileKey is available and reliable on
 * every platform this runtime targets.
 *
 * init is therefore implemented in full: it extracts the raw kernel
 * descriptor from the FileDescriptor object (the same offset every
 * other native in this runtime uses — FD_OFFSET, right after the
 * 8-byte object header), calls fstat(2), and writes st_dev and st_ino
 * into the corresponding instance fields through their
 * emitter-computed byte offsets.
 *
 * initIDs is a no-op: this runtime accesses every field through its
 * LLVM-computed byte offset and never consults JNI field IDs, so there
 * is nothing to cache.
 *
 * On fstat failure the native reports through the runtime's generic
 * throw helper, which the Java caller's `throws IOException` contract
 * turns into an IOException at the call site. That matches the
 * reference implementation exactly.
 *
 * ============================================================================
 * Field offsets
 * ============================================================================
 *
 * The byte offsets of st_dev and st_ino inside the FileKey object are
 * not hard-coded. They are looked up at run time by walking the
 * reflection metadata emitted by LlvmGlobalEmitter for the class — the
 * same metadata that produced every direct GET_FIELD / PUT_FIELD in
 * the generated bytecode. Any future JDK release that reorders or
 * renames the fields will therefore be picked up automatically.
 *
 * ============================================================================
 * Calling convention
 * ============================================================================
 *
 * init is an INSTANCE native: the receiver is the first argument
 * followed by the FileDescriptor. initIDs is a STATIC native: no
 * receiver argument.
 *
 * ============================================================================
 * The mangled names
 * ============================================================================
 *
 * LlvmRuntime.mangleMethod applies
 *     "fn_" + sanitize(class) + "_" + sanitize(method) + "_" + sanitize(desc)
 * where sanitize replaces every character outside [a-zA-Z0-9_] with a
 * single underscore. The emitter prefixes the result with "__jnative_".
 *
 *   class "sun/nio/ch/FileKey" -> "sun_nio_ch_FileKey"
 *
 *   init    desc "(Ljava/io/FileDescriptor;)V"
 *       -> "__jnative_fn_sun_nio_ch_FileKey_init__Ljava_io_FileDescriptor__V"
 *   initIDs desc "()V"
 *       -> "__jnative_fn_sun_nio_ch_FileKey_initIDs___V"
 *
 * The init name is the one the linker reported as undefined; initIDs
 * is emitted as well and would produce the same diagnostic on the next
 * rebuild if it were left out.
 *
 * ============================================================================
 * Class path
 * ============================================================================
 *
 * Compiler.getNativeResourcePath("sun/nio/ch/FileKey") does not strip
 * a leading "java/" — the class is in the sun.* namespace — so it
 * returns "jnative/sun/nio/ch/FileKey.c". That is the path this file
 * must live at for Compiler.extractSystemNativeSources to find it and
 * compile it into the executable.
 */

/*
 * Find the byte offset of an instance field, walking the superclass
 * chain. Uses the emitter-produced @reffields_* metadata, so the
 * returned offset agrees byte-for-byte with what generated bytecode
 * uses to address the same field. Returns -1 when the field is not
 * present in any class of the hierarchy.
 */
static int filekey_find_field_offset(ReflectionClass* cls, const char* field_name) {
    ReflectionClass* cur = cls;
    while (cur != NULL) {
        if (cur->fields != NULL) {
            ReflectionField** fp = cur->fields;
            while (*fp != NULL) {
                ReflectionField* f = *fp;
                if (f->name != NULL
                    && strcmp((const char*)f->name, field_name) == 0) {
                    return f->offset;
                }
                fp++;
            }
        }
        cur = cur->superclass;
    }
    return -1;
}

/*
 * private static native void initIDs();
 *
 * Called from FileKey.<clinit>. On HotSpot this hook caches the JNI
 * field IDs of st_dev and st_ino so the init native can write into
 * those fields without repeated lookups. This runtime accesses every
 * field through its LLVM-computed byte offset and never consults JNI
 * field IDs, so there is nothing to cache. The symbol must exist
 * because the class's static initializer emits a native call to it.
 *
 * STATIC native: no receiver argument.
 */
void __jnative_fn_sun_nio_ch_FileKey_initIDs___V(void) {
}

/*
 * private native void init(FileDescriptor fd) throws IOException;
 *
 * Extracts the raw kernel descriptor from the FileDescriptor object,
 * calls fstat(2) on it, and stores st_dev and st_ino into the
 * corresponding FileKey instance fields. On any failure the runtime's
 * generic throw helper reports the errno to the Java caller, matching
 * the reference implementation's `throws IOException` contract.
 */
void __jnative_fn_sun_nio_ch_FileKey_init__Ljava_io_FileDescriptor__V(
        void* this_key, void* fd_obj)
{
    if (this_key == NULL) {
        __jnative_throw_null_pointer_exception();
        return;
    }
    if (fd_obj == NULL) {
        __jnative_throw_null_pointer_exception();
        return;
    }

    /*
     * Extract the raw kernel descriptor. The FileDescriptor layout used
     * by this runtime is the same one every other native in the codebase
     * relies on: an 8-byte object header followed by the int32_t fd at
     * offset FD_OFFSET (see jnative_runtime.h).
     */
    int32_t fd = *(int32_t*)((char*)fd_obj + FD_OFFSET);
    if (fd < 0) {
        /* Descriptor already closed — the Java caller expects an
         * IOException from an init() on a stale FileDescriptor. */
        __jnative_throw_exception(NULL);
        return;
    }

    struct stat st;
    if (fstat(fd, &st) < 0) {
        __jnative_throw_exception(NULL);
        return;
    }

    ReflectionClass* cls = jnative_class_by_name("sun/nio/ch/FileKey");
    if (cls == NULL) {
        /*
         * The class was not registered for reflection; the Java-side
         * caller's fields stay at their default zeros. That is a
         * well-defined degenerate state: two FileKeys created the same
         * way would compare equal, and the Java-level FileLock code
         * would conservatively over-approximate overlapping locks —
         * the safe direction for a failure that should not occur.
         */
        return;
    }

    int off_dev = filekey_find_field_offset(cls, "st_dev");
    int off_ino = filekey_find_field_offset(cls, "st_ino");

    if (off_dev >= 0) {
        *(int64_t*)((char*)this_key + off_dev) = (int64_t)st.st_dev;
    }
    if (off_ino >= 0) {
        *(int64_t*)((char*)this_key + off_ino) = (int64_t)st.st_ino;
    }
}