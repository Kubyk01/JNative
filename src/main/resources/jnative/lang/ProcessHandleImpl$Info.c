/*
 * java.lang.ProcessHandleImpl$Info — native process-info reader.
 *
 * ============================================================================
 * Why this file exists
 * ============================================================================
 *
 * The inner class ProcessHandleImpl.Info declares a single native:
 *
 *     private native void info0(long pid);
 *
 * It is called once per Info instance, from the private Info(pid, isZombie)
 * constructor path, to populate the six instance fields that back the
 * ProcessHandle.Info accessor methods:
 *
 *     private long   user;
 *     private long   startTime;
 *     private long   totalTime;
 *     private String command;
 *     private String[] arguments;
 *     private String commandLine;
 *
 * The LLVM emitter records a call site for info0 in the generated IR, so
 * without a definition in the linked executable clang rejects
 * java/lang/ProcessHandleImpl$Info.ll with
 *
 *     error: use of undefined value
 *         '@__jnative_fn_java_lang_ProcessHandleImpl_Info_info0__J_V'
 *
 * ============================================================================
 * What this implementation provides
 * ============================================================================
 *
 * On Linux, all six fields can be recovered from the kernel's procfs:
 *
 *   /proc/<pid>/stat        — command, utime (field 14), stime (field 15),
 *                             starttime (field 22, clock ticks since boot)
 *   /proc/<pid>/status      — the real UID (the "Uid:" line)
 *   /proc/<pid>/cmdline     — NUL-separated argv, used both for the
 *                             arguments array and for the joined commandLine
 *   /proc/stat              — boot time ("btime <epoch-seconds>"), needed
 *                             to convert starttime from ticks-since-boot
 *                             to epoch milliseconds
 *
 * This is exactly the sequence the reference JDK's C implementation in
 * ProcessHandleImpl_unix.c performs. Reading procfs directly is simpler
 * than linking a platform abstraction and matches what every Linux
 * distribution's `ps` reads.
 *
 * ============================================================================
 * Failure handling
 * ============================================================================
 *
 * The Java-level Info() constructor already initialises the numeric fields
 * to -1 and leaves the reference fields null. That state is a fully
 * meaningful answer for ProcessHandle.Info:
 *
 *   command()          -> Optional.empty()
 *   commandLine()      -> Optional.empty()
 *   arguments()        -> Optional.empty()
 *   startInstant()     -> Optional.empty()
 *   totalCpuDuration() -> Optional.empty()
 *   user()             -> Optional.empty()
 *
 * Every failure mode in this file therefore degrades to "leave the field
 * as the Java constructor set it". A missing /proc entry (process died
 * between the caller's pid check and the native call, kernel thread with
 * no cmdline), an EACCES from a hardened procfs mount, a truncated read
 * — all of these produce empty Optionals rather than a fabricated value
 * or a spurious exception.
 *
 * Throwing IOException to match HotSpot's behaviour is deliberately not
 * done. HotSpot's caller is the JNI layer, which can turn an IOException
 * into a checked-exception path the Java code is prepared for; in a
 * compiled image the same throw would have to unwind through an event-
 * or stream-oriented caller that does not expect it. The safe direction
 * is to answer "no information" and let the JDK's own Optional semantics
 * carry that answer.
 *
 * ============================================================================
 * Field offsets
 * ============================================================================
 *
 * The byte offsets of Info's fields are not hard-coded. They are looked up
 * at run time by walking the reflection metadata emitted by
 * LlvmGlobalEmitter for the class — the same metadata that produced every
 * direct GET_FIELD / PUT_FIELD in the generated bytecode. Any future JDK
 * release that reorders or renames the fields will therefore be picked up
 * automatically: the walk finds them by name, and a field that no longer
 * exists simply leaves its Java-side default in place.
 */

/*
 * Read up to buf_size - 1 bytes from `path` into `buf`, NUL-terminate the
 * result, and return the number of bytes read (not counting the
 * terminator). Returns -1 when the file cannot be opened or read.
 *
 * EINTR is retried; every other error aborts the read and closes the
 * descriptor. The buffer is always NUL-terminated on return, even when
 * the read failed partway through, so callers never observe uninitialised
 * memory.
 */
static int info_read_file(const char* path, char* buf, size_t buf_size) {
    if (buf_size == 0) return -1;
    buf[0] = '\0';

    int fd = open(path, O_RDONLY);
    if (fd < 0) return -1;

    size_t total = 0;
    while (total + 1 < buf_size) {
        ssize_t n = read(fd, buf + total, buf_size - 1 - total);
        if (n < 0) {
            if (errno == EINTR) continue;
            int saved = errno;
            close(fd);
            errno = saved;
            buf[total] = '\0';
            return -1;
        }
        if (n == 0) break;
        total += (size_t)n;
    }
    buf[total] = '\0';
    close(fd);
    return (int)total;
}

/*
 * Find the byte offset of an instance field, walking the superclass chain.
 *
 * Uses the emitter-produced @reffields_* metadata, so the returned offset
 * agrees byte-for-byte with what generated bytecode uses to address the
 * same field. Returns -1 when the field is not present in any class of
 * the hierarchy.
 */
static int info_find_field_offset(ReflectionClass* cls, const char* field_name) {
    ReflectionClass* cur = cls;
    while (cur != NULL) {
        if (cur->fields != NULL) {
            ReflectionField** fp = cur->fields;
            while (*fp != NULL) {
                ReflectionField* f = *fp;
                if (f->name != NULL
                    && strcmp((const char*)f->name, field_name) == 0) {
                    return f->offset;
                }
                fp++;
            }
        }
        cur = cur->superclass;
    }
    return -1;
}

/*
 * Native info0(long pid) implementation. See the file header for the
 * overall design and the failure policy.
 */
void __jnative_fn_java_lang_ProcessHandleImpl_Info_info0__J_V(
        void* this_info, int64_t pid)
{
    if (this_info == NULL) {
        __jnative_throw_null_pointer_exception();
        return;
    }
    if (pid <= 0) {
        /* No process can have pid <= 0; nothing to look up. */
        return;
    }

    ReflectionClass* cls =
        jnative_class_by_name("java/lang/ProcessHandleImpl$Info");
    if (cls == NULL) {
        /* The class was not registered for reflection; leave the fields
         * at the values the Java constructor set. */
        return;
    }

    char path[64];
    char stat_buf[4096];

    /* -------- 1. /proc/<pid>/stat: command, utime, stime, starttime ----- */

    int n = snprintf(path, sizeof(path), "/proc/%lld/stat", (long long)pid);
    if (n <= 0 || (size_t)n >= sizeof(path)) return;
    if (info_read_file(path, stat_buf, sizeof(stat_buf)) < 0) {
        /* The process has gone away, or procfs is not accessible. */
        return;
    }

    /*
     * The comm field is delimited by the first '(' and the last ')' in the
     * whole file. Using the last ')' rather than the first is what makes
     * the parse robust against a command name that itself contains a ')'
     * character, e.g. "bash)worker".
     */
    char* lp = strchr(stat_buf, '(');
    char* rp = strrchr(stat_buf, ')');
    if (lp == NULL || rp == NULL || rp < lp) return;

    const char* command = lp + 1;
    *rp = '\0';                 /* terminate comm in place */
    char* fieldp = rp + 1;      /* points at the space after ')' */

    /*
     * Parse the remaining whitespace-separated numeric fields. Field
     * numbering starts at 1 with the pid; the fields we care about are:
     *
     *     field  3 = state
     *     field 14 = utime   (clock ticks)
     *     field 15 = stime   (clock ticks)
     *     field 22 = starttime (clock ticks since boot)
     *
     * `fieldp` currently points immediately after the comm field, i.e. at
     * the leading whitespace before field 3.
     */
    long long utime = -1;
    long long stime = -1;
    long long starttime_ticks = -1;

    int field_idx = 3;
    char* p = fieldp;
    while (*p != '\0' && field_idx <= 22) {
        while (*p == ' ' || *p == '\t') p++;
        if (*p == '\0' || *p == '\n') break;

        char* end;
        long long v = strtoll(p, &end, 10);
        if (end == p) break;    /* non-numeric field, stop */

        if (field_idx == 14) utime = v;
        else if (field_idx == 15) stime = v;
        else if (field_idx == 22) starttime_ticks = v;

        p = end;
        field_idx++;
    }

    long ticks_per_sec = sysconf(_SC_CLK_TCK);
    if (ticks_per_sec <= 0) ticks_per_sec = 100;    /* POSIX minimum */

    long long total_time_ms = 0;
    if (utime >= 0 && stime >= 0) {
        total_time_ms = (utime + stime) * 1000LL / ticks_per_sec;
    }

    /*
     * -------- 2. /proc/stat: boot time in epoch seconds --------
     *
     * starttime is measured in clock ticks since boot. To produce an
     * Instant in the Java layer we need epoch milliseconds, so the boot
     * time has to be recovered and added.
     */
    long long boot_time_sec = 0;
    {
        char procstat[16384];
        if (info_read_file("/proc/stat", procstat, sizeof(procstat)) > 0) {
            char* btime = strstr(procstat, "\nbtime ");
            if (btime == NULL && strncmp(procstat, "btime ", 6) == 0) {
                btime = procstat - 1;   /* emulate the leading \n */
            }
            if (btime != NULL) {
                boot_time_sec = strtoll(btime + 7, NULL, 10);
            }
        }
    }

    long long start_time_ms = 0;
    if (boot_time_sec > 0 && starttime_ticks >= 0) {
        start_time_ms = boot_time_sec * 1000LL
                      + starttime_ticks * 1000LL / ticks_per_sec;
    }

    /* -------- 3. /proc/<pid>/status: real UID -------- */

    long long user = -1;
    {
        char status_buf[8192];
        n = snprintf(path, sizeof(path), "/proc/%lld/status", (long long)pid);
        if (n > 0 && (size_t)n < sizeof(path)
            && info_read_file(path, status_buf, sizeof(status_buf)) > 0) {
            char* uid_line = strstr(status_buf, "\nUid:");
            if (uid_line == NULL && strncmp(status_buf, "Uid:", 4) == 0) {
                uid_line = status_buf - 1;
            }
            if (uid_line != NULL) {
                char* colon = strchr(uid_line, ':');
                if (colon != NULL) {
                    /* The line carries four IDs (real, effective, saved,
                     * filesystem); the first is what ProcessHandle.user()
                     * reports. */
                    user = strtoll(colon + 1, NULL, 10);
                }
            }
        }
    }

    /*
     * -------- 4. /proc/<pid>/cmdline: arguments and command line --------
     *
     * The file is a flat sequence of NUL-terminated strings, one per
     * argv element. A kernel thread (or a process whose exec has not
     * yet populated the array) has an empty file, which leaves both the
     * arguments array and the command line null.
     */
    void* args_array = NULL;
    void* commandline_str = NULL;
    int argc = 0;

    {
        char cmdline_buf[32768];
        n = snprintf(path, sizeof(path), "/proc/%lld/cmdline",
                     (long long)pid);
        int cmdline_len = -1;
        if (n > 0 && (size_t)n < sizeof(path)) {
            cmdline_len = info_read_file(path, cmdline_buf, sizeof(cmdline_buf));
        }

        if (cmdline_len > 0) {
            /* Count the NUL-separated segments. The final element may or
             * may not be NUL-terminated depending on whether the buffer
             * filled exactly; handle both cases. */
            int count = 0;
            int i = 0;
            while (i < cmdline_len) {
                int seg_start = i;
                while (i < cmdline_len && cmdline_buf[i] != '\0') i++;
                if (i > seg_start) count++;
                if (i < cmdline_len) i++;
            }
            argc = count;

            if (argc > 0) {
                void* arr = jnative_ref_array_of_class(
                    NULL, argc, "[Ljava/lang/String;");
                if (arr != NULL) {
                    void** slots = (void**)((char*)arr + JAVA_ARR_HDR);
                    int slot = 0;
                    i = 0;
                    while (i < cmdline_len && slot < argc) {
                        int seg_start = i;
                        while (i < cmdline_len && cmdline_buf[i] != '\0') i++;
                        if (i > seg_start) {
                            slots[slot++] = __jnative_make_string_obj(
                                cmdline_buf + seg_start, i - seg_start);
                        }
                        if (i < cmdline_len) i++;
                    }
                    args_array = arr;
                }

                /*
                 * Build the joined command line by walking the argument
                 * array and inserting single spaces between elements.
                 * This matches the reference JDK's ProcessHandleImpl
                 * semantics: commandLine() returns the concatenation with
                 * a space separator.
                 */
                if (args_array != NULL) {
                    void** slots = (void**)((char*)args_array + JAVA_ARR_HDR);
                    size_t total = 0;
                    for (int k = 0; k < argc; k++) {
                        if (slots[k] == NULL) continue;
                        int32_t l = 0;
                        __jnative_read_string_bytes(slots[k], &l);
                        if (total > 0) total += 1;
                        total += (size_t)l;
                    }
                    if (total > 0) {
                        char* joined = malloc(total + 1);
                        if (joined != NULL) {
                            size_t pos = 0;
                            for (int k = 0; k < argc; k++) {
                                if (slots[k] == NULL) continue;
                                int32_t l = 0;
                                const char* s = __jnative_read_string_bytes(
                                    slots[k], &l);
                                if (pos > 0) joined[pos++] = ' ';
                                memcpy(joined + pos, s, (size_t)l);
                                pos += (size_t)l;
                            }
                            joined[pos] = '\0';
                            commandline_str = __jnative_make_string_obj(
                                joined, (int32_t)pos);
                            free(joined);
                        }
                    }
                }
            }
        }
    }

    /* -------- 5. Write the fields -------- */

    if (user >= 0) {
        int off = info_find_field_offset(cls, "user");
        if (off >= 0) {
            *(int64_t*)((char*)this_info + off) = user;
        }
    }

    if (start_time_ms > 0) {
        int off = info_find_field_offset(cls, "startTime");
        if (off >= 0) {
            *(int64_t*)((char*)this_info + off) = start_time_ms;
        }
    }

    if (total_time_ms > 0) {
        int off = info_find_field_offset(cls, "totalTime");
        if (off >= 0) {
            *(int64_t*)((char*)this_info + off) = total_time_ms;
        }
    }

    if (command != NULL && command[0] != '\0') {
        int off = info_find_field_offset(cls, "command");
        if (off >= 0) {
            *(void**)((char*)this_info + off) =
                __jnative_make_string_obj(command, (int32_t)strlen(command));
        }
    }

    if (args_array != NULL) {
        int off = info_find_field_offset(cls, "arguments");
        if (off >= 0) {
            *(void**)((char*)this_info + off) = args_array;
        }
    }

    if (commandline_str != NULL) {
        int off = info_find_field_offset(cls, "commandLine");
        if (off >= 0) {
            *(void**)((char*)this_info + off) = commandline_str;
        }
    }
}

